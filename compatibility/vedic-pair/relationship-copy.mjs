export function relationshipCopy(c, context) {
 const a = relationshipTraits[c.sa];
 const b = relationshipTraits[c.sb];
 const same = c.sa === c.sb;
 const [title, baseIntro] = openings[c.type];
 const intro = c.type === 'same' && !same
  ? '月を受け持つ星は同じで、月の星座は違います。たとえば同じ予定でも、どこまで決めておきたいかはそれぞれです。2人が何を気にしているか、下の例で確かめてみてください。'
  : baseIntro;
 const [scene, next] = scenes[context];
 const variant = sceneVoices[context] ?? {};
 const lines = (sign, trait) => variant[sign] ?? trait.slice(1);
 const [aNeed,aVoice] = lines(c.sa,a);
 const [bNeed,bVoice] = lines(c.sb,b);
 const strengths = same
  ? `2人とも、${a[0]}のが持ち味です。片方が案を出したら、もう片方は「ここも決めておくと安心だね」と気づいたことを伝えてみてください。`
  : `Aさんは${a[0]}のが持ち味です。Bさんには、${b[0]}良さがあります。何かを決めるときは、2人が気づいたことを一つずつ出してみてください。自分だけでは見落としていた条件に気づけることがあります。`;
 const friction = same
  ? `${scene}、2人とも「${aNeed}」と思っていても、ちょうどいいタイミングや条件は違うんですよね。先に「どこまで変えていい？」と確認してみてください。`
  : `${scene}の話です。Aさんは「${aNeed}」。Bさんは「${bNeed}」。このまま結論だけ急ぐと、相手が何を気にしているのか分からないまま話が進んでしまうんですね。`;
 return {title,intro,strengths,friction,next,voices:[aVoice, same ? 'うん。私が気になるところも、一つ聞いてもらえる？' : bVoice]};
}
