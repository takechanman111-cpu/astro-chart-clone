function solarReturnParagraphs(sr) {
  if(!sr.houses?.length) return ['今年のハウス情報を取得できていません。再計算してください。'];
  const sun=sr.planets.find(p=>p.body==='Sun'),moon=sr.planets.find(p=>p.body==='Moon');
  const theme=SOLAR_YEAR_HOUSES[sun.house],emotional=SOLAR_YEAR_HOUSES[moon.house];
  const rows=[`<b>今年のテーマは「${theme[0]}」。</b>${theme[1]}`,`<b>気をつけたいこと：</b>${theme[2]}`,`<b>気持ちが向きやすいのは、${HOUSE_PLAIN[moon.house]}。</b>${SIGN_COMFORT[moon.sign_ja]}${sun.house===moon.house?'今年力を入れたいことと、気持ちの向かう先が同じ分野です。頑張る時間と休む時間の区切りを大切にしましょう。':`目標を進める一方で、この分野にも時間を残しましょう。${emotional[1]}`}`];
  const hits=findAspects(sr.planets.map(p=>p.longitude)).filter(a=>(a.p1===0||a.p1===1)&&Number(a.orb)<=5&&SOLAR_PAIR[`${sr.planets[a.p1].body_ja}|${sr.planets[a.p2].body_ja}`]).sort((a,b)=>Number(a.orb)-Number(b.orb)).slice(0,4);
  for(const a of hits){
    const p=sr.planets[a.p1],q=sr.planets[a.p2],pair=SOLAR_PAIR[`${p.body_ja}|${q.body_ja}`];
    if(!pair)continue;
    const tension=['□','☍'].includes(a.asp.sym),conj=a.asp.sym==='☌';
    const tensionText=ASPECT_PAIR_READING[`${p.body_ja}|${q.body_ja}`]?.tension; 
    rows.push(`<b>${tension?'今年の課題':conj?'今年強く出やすいこと':'今年生かしたい強み'}：${pair[0]}。</b>${tension?(tensionText?`${tensionText}に注意したい年です。`:'気持ちと予定がかみ合わず、無理をしやすい年です。'):conj?'思いが行動に表れやすくなるため、何に時間を使うかを自分で決めたい年です。':'普段ならためらうことにも取り組みやすいので、小さく試してみましょう。'}${pair[1]}<br><small>今年の${p.body_ja}（第${p.house}ハウス）${a.asp.sym}${q.body_ja}（第${q.house}ハウス）、ずれ${a.orb}°。</small>`);
  }
  rows.push(`<b>今年の配置：</b>太陽は${sun.sign_ja}・第${sun.house}ハウス、月は${moon.sign_ja}・第${moon.house}ハウスです。上の中心テーマは太陽のハウス、気持ちの向かう先は月のハウスと星座、強みと課題は太陽・月に関わる主な角度から読んでいます。`);
  rows.push(`<b>対象の一年と計算条件：</b>${new Intl.DateTimeFormat('ja-JP',{timeZone:'Asia/Tokyo',dateStyle:'medium',timeStyle:'short'}).format(new Date(sr.return_time_utc))}（日本時間）から次の太陽回帰まで。太陽回帰は、太陽が出生時と同じ位置へ戻る瞬間の図です。出生地の座標（北緯${sr.location.latitude}°・東経${sr.location.longitude}°）、等分ハウスで計算しています。誕生日を過ごす場所を変更する入力には、まだ対応していません。`);
  return rows;
}
